import 'package:isar/isar.dart';

part 'eway_bill.g.dart';

/// E-Way Bill for goods movement under GST.
/// Required for movement of goods where consignment value exceeds ₹50,000.
@collection
class EWayBill {
  Id id = Isar.autoIncrement;

  /// E-Way Bill Number (12-digit number from portal)
  @Index(unique: true)
  String? ewayBillNumber;

  /// E-Way Bill date
  DateTime? ewayBillDate;

  /// Valid until date
  DateTime? validUpto;

  /// Reference to invoice/purchase
  int? documentId;
  String documentNumber = '';
  String documentType = 'tax_invoice'; // tax_invoice, delivery_challan, etc.
  DateTime documentDate = DateTime.now();

  /// Supply type: 'O' = Outward, 'I' = Inward
  String supplyType = 'O';

  /// Sub-supply type (1-14 as per e-way bill rules)
  /// 1=Supply, 2=Export, 3=Job Work, 4=For Own Use, etc.
  int subSupplyType = 1;

  /// Sub-supply description
  String? subSupplyDescription;

  /// Document type code
  String docTypeCode = 'INV'; // INV, CHL, BIL, etc.

  /// Party (recipient/supplier) details
  int? partyId;
  String partyName = '';
  String? partyGstin;
  String? partyState;

  /// Dispatch from (if different from business address)
  String? dispatchFromName;
  String? dispatchFromAddress;
  String? dispatchFromState;
  String? dispatchFromGstin;

  /// Ship to (if different from party address)
  String? shipToName;
  String? shipToAddress;
  String? shipToState;
  String? shipToGstin;

  /// Transporter details
  String? transporterId;
  String? transporterName;

  /// Transportation mode: 'road', 'rail', 'air', 'ship'
  String transportationMode = 'road';

  /// Vehicle number (for road transport)
  String? vehicleNumber;

  /// Vehicle type: 'regular', 'over_dimensional'
  String vehicleType = 'regular';

  /// Place of change of vehicle (if applicable)
  String? placeOfChangeOfVehicle;

  /// State of change of vehicle
  String? stateOfChangeOfVehicle;

  /// Distance in kilometers
  double distance = 0.0;

  /// Value of goods
  double taxableValue = 0.0;

  /// Taxes
  double cgst = 0.0;
  double sgst = 0.0;
  double igst = 0.0;
  double cess = 0.0;
  double totalValue = 0.0;

  /// Line items for the e-way bill
  List<EWayBillLineItem> items = [];

  /// Status: 'generated', 'cancelled', 'expired', 'extended'
  String status = 'generated';

  /// Cancelled reason (if cancelled)
  String? cancelledReason;
  DateTime? cancelledDate;

  /// Extension count
  int extensionCount = 0;

  /// Created timestamp
  DateTime createdAt = DateTime.now();

  /// Generated by (user/app)
  String generatedBy = 'app';

  /// Remarks
  String? remarks;
}

@embedded
class EWayBillLineItem {
  int? itemId;
  String? itemName;
  String? hsnCode;
  double quantity = 0.0;
  String? unit;
  double taxableValue = 0.0;
  double gstRate = 0.0;
}